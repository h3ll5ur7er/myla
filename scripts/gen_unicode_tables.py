#!/usr/bin/env python3
"""Generate the identifier table of the self-hosted lexer (MYLA-84, D72).

An identifier is `_` or an XID_Start character, then XID_Continue characters:
Unicode's identifier syntax, the one Python's `str.isidentifier` checks. The
non-ASCII ranges of both sets are taken from the Python running this script
and written to selfhost/unicode.my: each range as 12 hex digits (first and
last code point, 6 each) in a string constant, binary-searched in place, so a
lookup allocates nothing. (Until MYLA-219 it also wrote the Python lexer's
table.)

A fixed table, not the running Python's `unicodedata`, so the lexer doesn't
depend on who runs it; `UNICODE_VERSION` records which Unicode it came from.
Rerun after a Python upgrade to move to a newer Unicode:

    python3 scripts/gen_unicode_tables.py
"""
from __future__ import annotations

import os
import sys
import unicodedata

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), os.pardir))
MY_OUT = os.path.join(REPO, "selfhost", "unicode.my")


def ranges(member) -> list[tuple[int, int]]:
    """The maximal runs of non-ASCII code points for which `member` holds."""
    out: list[tuple[int, int]] = []
    start = None
    for cp in range(0x80, 0x110000 + 1):
        inside = cp <= 0x10FFFF and not 0xD800 <= cp <= 0xDFFF and member(chr(cp))
        if inside and start is None:
            start = cp
        elif not inside and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def xid_start(c: str) -> bool:
    return c.isidentifier()


def xid_continue(c: str) -> bool:
    return ("a" + c).isidentifier()


def myla_module(start, cont) -> str:
    def const(name, rs):
        text = "".join(f"{a:06X}{b:06X}" for a, b in rs)
        chunks = [text[i:i + 96] for i in range(0, len(text), 96)]
        return f"const {name}: str = " + " + ".join(f'"{c}"' for c in chunks)

    return f'''// unicode.my -- identifier characters beyond ASCII (MYLA-84, D72):
// generated by scripts/gen_unicode_tables.py from Unicode {unicodedata.unidata_version}; do not edit.
//
// An identifier is `_` or an XID_Start character, then XID_Continue
// characters. Each table is a run of 12 hex digits per range (first and last
// code point, 6 each), sorted, searched in place.

pub const UNICODE_VERSION: str = "{unicodedata.unidata_version}"

{const("XID_START", start)}

{const("XID_CONTINUE", cont)}

// `_`, an ASCII letter, or a non-ASCII XID_Start character.
#test(95)[true]
#test(246)[true]
#test(183)[false]
#test(8364)[false]
pub fun is_xid_start(c: int32) -> bool {{
    if c < 128 {{ return c == 95 || (c >= 65 && c <= 90) || (c >= 97 && c <= 122) }}
    return in_table(XID_START, c)
}}

// An ASCII letter, digit or `_`, or a non-ASCII XID_Continue character.
#test(48)[true]
#test(183)[true]
#test(769)[true]
#test(8364)[false]
pub fun is_xid_continue(c: int32) -> bool {{
    if c < 128 {{ return c == 95 || (c >= 65 && c <= 90) || (c >= 97 && c <= 122) || (c >= 48 && c <= 57) }}
    return in_table(XID_CONTINUE, c)
}}

// Whether `c` is in one of the ranges of `table` (binary search).
#test("a", 86)[false]
#test("x", 27)[false]
#test("y", 60)[false]
fun in_table(table: str, c: int32) -> bool {{
    var lo = 0
    var hi = len(table) / 12
    while lo < hi {{
        let mid = (lo + hi) / 2
        if hex6(table, mid * 12 + 6) < c {{
            lo = mid + 1
        }} else {{
            hi = mid
        }}
    }}
    return lo < len(table) / 12 && hex6(table, lo * 12) <= c
}}

// The 6 hex digits of `table` from `at`.
fun hex6(table: str, at: int32) -> int32 {{
    var v = 0
    for i in at..at + 6 {{
        let d = table[i]
        if d <= '9' {{
            v = v * 16 + ((d - '0') as int32)
        }} else {{
            v = v * 16 + ((d - 'A') as int32) + 10
        }}
    }}
    return v
}}
'''


def main() -> int:
    start = ranges(xid_start)
    cont = ranges(xid_continue)
    with open(MY_OUT, "w", encoding="utf-8") as fh:
        fh.write(myla_module(start, cont))
    print(f"Unicode {unicodedata.unidata_version}: {len(start)} XID_Start and {len(cont)} XID_Continue ranges")
    return 0


if __name__ == "__main__":
    sys.exit(main())
