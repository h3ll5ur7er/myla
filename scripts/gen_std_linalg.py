def quaternion_module(p: Precision) -> str:
    out = HEADER.format(module="quaternion", suffix=p.suffix, what="quaternions", scalar=p.scalar,
                        other_scalar=p.other_scalar, other_suffix=p.other_suffix)
    return out + fill(QUATERNION, p)


def modules() -> dict[str, str]:
    out = {}
    for p in PRECISIONS:
        out[f"vector{p.suffix}.my"] = vector_module(p)
        out[f"matrix{p.suffix}.my"] = matrix_module(p)
        out[f"quaternion{p.suffix}.my"] = quaternion_module(p)
    return out


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for name, text in modules().items():
        path = os.path.join(STD, name)
        if check:
            try:
                with open(path, encoding="utf-8") as fh:
                    if fh.read() != text:
                        stale.append(name)
            except FileNotFoundError:
                stale.append(name)
        else:
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(text)
    if stale:
        print("stale (run python3 scripts/gen_std_linalg.py): " + ", ".join("lib/std/" + s for s in stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
