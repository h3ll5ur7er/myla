#!/usr/bin/env python3
"""Generate std.vector, std.matrix and std.quaternion and their float32 twins
std.vector32, std.matrix32 and std.quaternion32 (D201, MYLA-587).

Myla has no bound that names "a float type" and no overloading, so each
precision gets modules of its own with the same names, written here from one
template: `float64` in std.vector, `float32` in std.vector32, and so on. Each
module converts into its twin (`to_f32`, `to_f64`), which is why the twins
import each other.

    python3 scripts/gen_std_linalg.py           # writes the six modules
    python3 scripts/gen_std_linalg.py --check   # fails if one isn't current
"""
from __future__ import annotations

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STD = os.path.join(ROOT, "lib", "std")

AXES = ["x_axis", "y_axis", "z_axis", "w_axis"]


class Precision:
    def __init__(self, suffix: str, scalar: str, other_suffix: str, other_scalar: str, conv: str, tag: str) -> None:
        self.suffix = suffix              # "" or "32": the module's name ends with it
        self.scalar = scalar              # float64 or float32
        self.other_suffix = other_suffix  # the twin's
        self.other_scalar = other_scalar
        self.conv = conv                  # to_f32 or to_f64
        self.tag = tag                    # F32 or F64: the twin's types are imported as Vec3F32


PRECISIONS = [
    Precision("", "float64", "32", "float32", "to_f32", "F32"),
    Precision("32", "float32", "", "float64", "to_f64", "F64"),
]

HEADER = """// std.{module}{suffix}: {what} of {scalar} (D201, MYLA-587).
//
// GENERATED by scripts/gen_std_linalg.py, with its {other_scalar} twin
// std.{module}{other_suffix}, from one template: edit the script, not this file.
//
"""


def comps(n: int) -> list[str]:
    return ["x", "y", "z", "w"][:n]


def fill(text: str, p: Precision, **kw: str) -> str:
    """`text` with `@S@` the scalar type and the other tokens in `kw`."""
    text = text.replace("@S@", p.scalar).replace("@OS@", p.other_scalar).replace("@CONV@", p.conv)
    text = text.replace("@O@", p.tag).replace("@SFX@", p.suffix).replace("@OSFX@", p.other_suffix)
    for k, v in kw.items():
        text = text.replace("@" + k + "@", v)
    return text


